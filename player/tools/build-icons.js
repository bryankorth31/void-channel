// Copies the icons the player uses from the brand kit (brand-kit/icons/ui) into player/src/icons.js, so the
// player has no runtime file dependencies and the brand kit stays the single source of truth.
// Run after changing an icon:  node player/tools/build-icons.js
const fs = require('fs');
const path = require('path');
const SRC = path.join(__dirname, '..', '..', 'brand-kit', 'icons', 'ui');
const NEED = ['play', 'pause', 'back10', 'fwd30', 'fwd10', 'volume', 'volume-low', 'mute', 'captions', 'pip', 'fullscreen', 'exit-fullscreen', 'speed', 'next', 'prev', 'download', 'retry', 'flag', 'close', 'no-signal', 'check'];
const out = {};
for (const n of NEED) {
  const svg = fs.readFileSync(path.join(SRC, n + '.svg'), 'utf8').trim()
    .replace(' width="24" height="24"', '').replace('<svg ', '<svg aria-hidden="true" focusable="false" ');
  out[n] = svg;
}
const js = '// Generated by player/tools/build-icons.js from brand-kit/icons/ui. Do not edit by hand.\n'
  + '(function (root) { root.VoidIcons = ' + JSON.stringify(out) + '; })(typeof self !== \'undefined\' ? self : this);\n';
fs.writeFileSync(path.join(__dirname, '..', 'src', 'icons.js'), js);
console.log(Object.keys(out).length, 'icons -> player/src/icons.js');
